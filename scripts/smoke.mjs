import fs from 'node:fs/promises';
import assert from 'node:assert/strict';
const origin=process.env.STUDIO_URL||'http://127.0.0.1:8787';
if(!['127.0.0.1','localhost'].includes(new URL(origin).hostname))throw Error('Smoke writes are local only.');
const vars=await fs.readFile(new URL('../.env.accounts',import.meta.url),'utf8');
const password=vars.match(/^OWNER_PASSWORD=(.+)$/m)?.[1];
const login=await fetch(origin+'/api/login',{method:'POST',headers:{Origin:origin,'Content-Type':'application/json'},body:JSON.stringify({username:'bcraighead',password})});
assert.equal(login.status,200);const cookie=login.headers.get('set-cookie').split(';')[0];
const req=(path,options={})=>fetch(origin+'/api'+path,{...options,headers:{Origin:origin,Cookie:cookie,'Content-Type':'application/json',...options.headers}});
const {starterProject}=await import('../public/lib/site.js');
const p=starterProject();p.name='Integration verification';
const created=await (await req('/projects',{method:'POST',body:JSON.stringify({project:p})})).json();
assert.ok(created.id);const url='/projects/'+created.id;
p.tagline+=' · updated by smoke test';
const save=await req(url,{method:'PUT',body:JSON.stringify({project:p,revision:1})});assert.equal(save.status,200);
const stale=await req(url,{method:'PUT',body:JSON.stringify({project:p,revision:1})});assert.equal(stale.status,409);
assert.equal((await(await req(url+'/revisions')).json()).revisions.length,2);
assert.ok((await(await req(url+'/export')).json()).files['index.html']);
const publish=await req(url+'/publish',{method:'POST',body:JSON.stringify({revision:2,confirm:'wrong'})});assert.equal(publish.status,409);
const rejected=await req(url,{method:'PUT',headers:{Origin:'https://other.example'},body:JSON.stringify({project:p,revision:2})});assert.equal(rejected.status,403);
const logout=await req('/logout',{method:'POST'});assert.match(logout.headers.get('set-cookie'),/Max-Age=0/);
console.log('Authenticated D1 smoke passed: create, save, stale-save conflict, revisions, export, publish guard, CSRF, logout. Local test project retained.');
